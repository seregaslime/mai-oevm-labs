# ---------- helpers ----------
def _fonts(run, name, size, bold=False, italic=False):
    run.font.name = name
    run.font.size = Pt(size)
    run.font.bold = bold
    run.font.italic = italic
    rf = run._r.get_or_add_rPr().get_or_add_rFonts()
    for a in ("w:ascii", "w:hAnsi", "w:eastAsia", "w:cs"):
        rf.set(qn(a), name)


def _new_par():
    p = doc.add_paragraph()
    body.remove(p._p)
    sect.addprevious(p._p)
    return p


def _spacing(p, before=0, after=160, line=1.5):
    pf = p.paragraph_format
    pf.space_before = Pt(before / 20)
    pf.space_after = Pt(after / 20)
    pf.line_spacing = line


def heading(text, level=1):
    p = _new_par()
    p._p.style = f"Heading{level}"
    _spacing(p, 240, 160)
    r = p.add_run(text)
    _fonts(r, TNR, 16 if level == 1 else 14, bold=True)
    r.font.color.rgb = RGBColor(0, 0, 0)
    return p


def para(text="", indent=True, align=WD_ALIGN_PARAGRAPH.JUSTIFY, after=160, bold=False,
         parts=None):
    """Обычный абзац; parts - список (текст, жирный) для смешанного начертания."""
    p = _new_par()
    _spacing(p, 0, after)
    p.alignment = align
    if indent:
        p.paragraph_format.first_line_indent = Cm(1.25)
    for t, bb in parts or [(text, bold)]:
        _fonts(p.add_run(t), TNR, 14, bold=bb)
    return p


def code(lines, size=10):
    for ln in lines:
        p = _new_par()
        _spacing(p, 0, 0, 1.0)
        p.alignment = WD_ALIGN_PARAGRAPH.LEFT
        _fonts(p.add_run(ln if ln else " "), MONO, size)


def bullet(text):
    p = _new_par()
    p._p.style = "ListParagraph"
    _spacing(p, 0, 60)
    numpr = OxmlElement("w:numPr")
    ilvl, num = OxmlElement("w:ilvl"), OxmlElement("w:numId")
    ilvl.set(qn("w:val"), "0")
    num.set(qn("w:val"), "2")
    numpr.extend([ilvl, num])
    p._p.pPr.pStyle.addnext(numpr)
    _fonts(p.add_run(text), TNR, 14)


def picture(path, width_cm, caption):
    p = _new_par()
    _spacing(p, 120, 60, 1.0)
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    p.add_run().add_picture(path, width=Cm(width_cm))
    c = _new_par()
    _spacing(c, 0, 160, 1.0)
    c.alignment = WD_ALIGN_PARAGRAPH.CENTER
    _fonts(c.add_run(caption), TNR, 12)


def placeholder(text):
    p = _new_par()
    _spacing(p, 120, 60, 1.0)
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    r = p.add_run(text)
    _fonts(r, TNR, 14, bold=True)
    r.font.highlight_color = 7  # жёлтый


def table(rows, widths_cm, bold_header=True, size=14):
    t = doc.add_table(rows=len(rows), cols=len(rows[0]))
    body.remove(t._tbl)
    sect.addprevious(t._tbl)
    t.style = None
    borders = OxmlElement("w:tblBorders")
    for side in ("top", "left", "bottom", "right", "insideH", "insideV"):
        e = OxmlElement(f"w:{side}")
        e.set(qn("w:val"), "single")
        e.set(qn("w:sz"), "4")
        e.set(qn("w:color"), "auto")
        borders.append(e)
    look = t._tbl.tblPr.find(qn("w:tblLook"))
    if look is not None:
        look.addprevious(borders)
    else:
        t._tbl.tblPr.append(borders)
    t.alignment = 1
    for i, row in enumerate(rows):
        for j, val in enumerate(row):
            cell = t.cell(i, j)
            cell.width = Cm(widths_cm[j])
            p = cell.paragraphs[0]
            p.alignment = WD_ALIGN_PARAGRAPH.CENTER
            _spacing(p, 0, 0, 1.0)
            _fonts(p.add_run(str(val)), TNR, size, bold=bold_header and i == 0)
    after = _new_par()
    _spacing(after, 0, 120, 1.0)
    return t



